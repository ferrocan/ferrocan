//! `can-hal-mcan` in internal loopback on the NUCLEO-G431KB, whose FDCAN1
//! pins aren't brought out (its only TX pin, PA12, is USB D+): internal
//! loopback needs none.
//!
//! - Every kind of classic frame (standard and extended IDs, data and
//!   remote, every DLC from 0 to 15) and of FD frame (every length, with and
//!   without bit-rate switching and the error state indicator) is sent and
//!   must come back both as a received frame and as a transmission reported
//!   sent.
//! - Three frames are handed over at once, a fourth must find no room, and
//!   an abort of the last is reported in its place in order.
//! - Reconfigured as a classic channel, an FD frame is refused.
//!
//! On success the green LED (LD2) blinks slowly; on a failure, fast.
//!
//! ```sh
//! cargo run-mcan-loopback
//! ```

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use can_hal::{BusState, BusStatus, CanFdFrame, CanFrame, CanId, ConfirmedTransmit, Event, Frame, Outcome, SamplePoint, Statistics, TransmitId, TryTransmitError};
use can_hal_mcan::{BitTiming, Can, Clock, Config, Error, Mode, Peripheral, State};
use defmt::{Debug2Format, error, info};
use defmt_rtt as _;
use embassy_executor::Spawner;
use embassy_stm32::gpio::{Level, Output, Speed};
use embassy_stm32::interrupt::typelevel::{FDCAN1_IT0, Handler, Interrupt};
use embassy_stm32::rcc::{self, Pll, PllMul, PllPreDiv, PllQDiv, PllRDiv, PllSource, Sysclk};
use embassy_time::{Duration, Timer, with_timeout};
use panic_probe as _;

/// FDCAN1's kernel clock: PLL Q, 80 MHz.
const CAN_CLOCK_HZ: u32 = 80_000_000;
const EVENTS: usize = 32;
const NOMINAL_BITRATE: u32 = 500_000;
const DATA_BITRATE: u32 = 2_000_000;
const TIMEOUT: Duration = Duration::from_millis(100);

/// Embassy's time, for the driver's timestamps and timeouts.
struct EmbassyClock;

impl Clock for EmbassyClock {
    type Instant = embassy_time::Instant;

    fn now() -> Self::Instant {
        embassy_time::Instant::now()
    }

    fn deadline(timeout: core::time::Duration) -> Self::Instant {
        let micros = u64::try_from(timeout.as_micros()).unwrap_or(u64::MAX);
        embassy_time::Instant::now().saturating_add(Duration::from_micros(micros))
    }

    fn has_passed(deadline: &Self::Instant) -> bool {
        embassy_time::Instant::now() >= *deadline
    }
}

type Channel = Can<EmbassyClock, EVENTS>;

static STATE: State<EmbassyClock, EVENTS> = State::new();

struct CanInterrupt;

impl Handler<FDCAN1_IT0> for CanInterrupt {
    unsafe fn on_interrupt() {
        STATE.on_interrupt();
    }
}

embassy_stm32::bind_interrupts!(struct Irqs {
    FDCAN1_IT0 => CanInterrupt;
});

/// HSI16 through the PLL: 160 MHz system clock (R), 80 MHz for FDCAN (Q).
fn clocks() -> embassy_stm32::Config {
    let mut config = embassy_stm32::Config::default();
    config.rcc.pll = Some(Pll {
        source: PllSource::HSI,
        prediv: PllPreDiv::DIV4,
        mul: PllMul::MUL80,
        divp: None,
        divq: Some(PllQDiv::DIV4),
        divr: Some(PllRDiv::DIV2),
    });
    config.rcc.sys = Sysclk::PLL1_R;
    config.rcc.boost = true;
    config.rcc.mux.fdcansel = rcc::mux::Fdcansel::PLL1_Q;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = embassy_stm32::init(clocks());
    let mut led = Output::new(p.PB8, Level::Low, Speed::Low);

    // FDCAN1's bus clock; its kernel clock is PLL Q, by the mux above.
    embassy_stm32::pac::RCC.apb1enr1().modify(|w| w.set_fdcanen(true));
    let _ = embassy_stm32::pac::RCC.apb1enr1().read();

    let nominal = BitTiming::solve_nominal(CAN_CLOCK_HZ, NOMINAL_BITRATE, SamplePoint::from_per_mille(875)).unwrap();
    let data = BitTiming::solve_data(CAN_CLOCK_HZ, DATA_BITRATE, SamplePoint::from_per_mille(800)).unwrap();
    info!("nominal {}: {} bit/s; data {}: {} bit/s", nominal, nominal.bitrate(CAN_CLOCK_HZ), data, data.bitrate(CAN_CLOCK_HZ));
    let config = Config::new(nominal).with_data(data).with_mode(Mode::SilentLoopback);
    // SAFETY: FDCAN1's registers and message RAM on the STM32G4, used by
    // nothing else.
    let peripheral = unsafe { Peripheral::new(0x4000_6400, 0x4000_A400) };
    let mut can = Can::new(peripheral, &STATE, config).unwrap();
    FDCAN1_IT0::unpend();
    // SAFETY: its handler is bound above.
    unsafe { FDCAN1_IT0::enable() };
    can.start().unwrap();
    info!("synchronised: {}", can.is_synchronized());

    let mut failures = 0u32;
    failures += every_classic_frame(&mut can).await;
    failures += every_fd_frame(&mut can).await;
    failures += three_at_once(&mut can).await;
    failures += classic_only(&mut can, Config::new(nominal).with_mode(Mode::SilentLoopback)).await;

    info!("bus state {}, counters {}", Debug2Format(&can.bus_state()), Debug2Format(&can.error_counters()));
    info!("statistics {}", Debug2Format(&can.statistics()));
    if can.bus_state() != Ok(BusState::ErrorActive) {
        error!("not error active");
        failures += 1;
    }
    if failures == 0 {
        info!("loopback: all passed");
    } else {
        error!("loopback: {} failures", failures);
    }

    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after_millis(period).await;
    }
}

fn ids() -> [CanId; 2] {
    [CanId::new_standard(0x123).unwrap(), CanId::new_extended(0x1234_5678).unwrap()]
}

/// Sends `frame`, which must come back received unchanged and reported sent.
async fn round_trip(can: &mut Channel, frame: &Frame) -> u32 {
    let tx = match ConfirmedTransmit::<Frame>::try_transmit(can, frame) {
        Ok(tx) => tx,
        Err(e) => {
            error!("{}: transmit {}", Debug2Format(frame), Debug2Format(&e));
            return 1;
        }
    };
    let (mut received, mut sent) = (false, false);
    while !(received && sent) {
        match next(can).await {
            Some(Event::Received(r)) if r.frame() == frame => received = true,
            Some(Event::Transmitted { id, outcome: Outcome::Sent(_) }) if id == tx => sent = true,
            other => {
                error!("{}: unexpected {}", Debug2Format(frame), Debug2Format(&other));
                return 1;
            }
        }
    }
    0
}

async fn every_classic_frame(can: &mut Channel) -> u32 {
    let data = [0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];
    let (mut frames, mut failures) = (0, 0);
    for id in ids() {
        for dlc in 0..=15 {
            for frame in [CanFrame::new_with_dlc(id, &data[..dlc.min(8)], dlc).unwrap(), CanFrame::new_remote(id, dlc).unwrap()] {
                frames += 1;
                failures += round_trip(can, &Frame::Can(frame)).await;
            }
        }
    }
    info!("every classic frame: {} frames, {} failures", frames, failures);
    failures
}

async fn every_fd_frame(can: &mut Channel) -> u32 {
    let mut data = [0u8; 64];
    for (i, byte) in (0u8..).zip(data.iter_mut()) {
        *byte = i.wrapping_mul(37) ^ 0x5A;
    }
    let (mut frames, mut failures) = (0, 0);
    for id in ids() {
        for len in [0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64] {
            for (brs, esi) in [(false, false), (true, false), (false, true), (true, true)] {
                frames += 1;
                failures += round_trip(can, &Frame::Fd(CanFdFrame::new(id, &data[..len], brs, esi).unwrap())).await;
            }
        }
    }
    info!("every FD frame: {} frames, {} failures", frames, failures);
    failures
}

/// Three frames handed over at once, a fourth finding no room, and the third
/// aborted: the reports come in the order handed over.
async fn three_at_once(can: &mut Channel) -> u32 {
    let frame = |n: u8| Frame::Fd(CanFdFrame::new(CanId::new_standard(0x100 + u16::from(n)).unwrap(), &[n; 64], true, false).unwrap());
    let ids: [TransmitId; 3] = [0, 1, 2].map(|n| ConfirmedTransmit::<Frame>::try_transmit(can, &frame(n)).unwrap());
    let mut failures = 0;
    if !matches!(ConfirmedTransmit::<Frame>::try_transmit(can, &frame(3)), Err(TryTransmitError::Full)) {
        error!("a fourth frame found room");
        failures += 1;
    }
    ConfirmedTransmit::<Frame>::abort(can, ids[2]).unwrap();

    let mut reports = [None; 3];
    let mut received = 0;
    let mut reported = 0;
    while reported < 3 {
        match next(can).await {
            Some(Event::Transmitted { id, outcome }) => {
                if id != ids[reported] {
                    error!("report {} for {}, expected {}", reported, Debug2Format(&id), Debug2Format(&ids[reported]));
                    failures += 1;
                }
                reports[reported] = Some(outcome);
                reported += 1;
            }
            Some(Event::Received(_)) => received += 1,
            other => {
                error!("unexpected {}", Debug2Format(&other));
                failures += 1;
                break;
            }
        }
    }
    // The third was aborted in time, or was already on its way and sent.
    let third_aborted = matches!(reports[2], Some(Outcome::Aborted(_)));
    let expected_received = if third_aborted { 2 } else { 3 };
    while received < expected_received {
        match next(can).await {
            Some(Event::Received(_)) => received += 1,
            other => {
                error!("waiting for frames: {}", Debug2Format(&other));
                failures += 1;
                break;
            }
        }
    }
    if let Some(other) = next(can).await {
        error!("after three at once: {}", Debug2Format(&other));
        failures += 1;
    }
    info!("three at once: reports {}, {} received, {} failures", Debug2Format(&reports), received, failures);
    if !reports[..2].iter().all(|o| matches!(o, Some(Outcome::Sent(_)))) {
        error!("the first two weren't both sent");
        failures += 1;
    }
    failures
}

/// Reconfigured without a data phase, the channel refuses FD frames and
/// still carries classic ones.
async fn classic_only(can: &mut Channel, config: Config) -> u32 {
    let mut failures = 0;
    can.reconfigure(config).unwrap();
    can.start().unwrap();
    let fd = Frame::Fd(CanFdFrame::new(ids()[0], &[1; 12], false, false).unwrap());
    let refused = ConfirmedTransmit::<Frame>::try_transmit(can, &fd);
    if refused != Err(TryTransmitError::Backend(Error::FdDisabled)) {
        error!("an FD frame on a classic channel: {}", Debug2Format(&refused));
        failures += 1;
    }
    failures += round_trip(can, &Frame::Can(CanFrame::new(ids()[1], &[9, 8, 7]).unwrap())).await;
    info!("classic only: {} failures", failures);
    failures
}

async fn next(can: &mut Channel) -> Option<Event<Frame, embassy_time::Instant>> {
    with_timeout(TIMEOUT, can.next_event()).await.ok()
}
