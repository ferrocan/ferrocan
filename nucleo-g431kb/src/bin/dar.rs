//! How ST's FDCAN reports a failed single-shot (DAR) transmission, on the
//! NUCLEO-G431KB with FDCAN1 on PA12 (TX, CN4 pin 5) and PA11 (RX, CN4 pin
//! 13).
//!
//! - With a jumper from CN4-5 to CN4-13 the controller hears its own frames
//!   and nobody acknowledges them: acknowledgement errors, as on a bus with
//!   no other node.
//! - With no jumper RX idles recessive on its pull-up and the first dominant
//!   bit fails: bit errors. They raise the TEC in error passive too, so the
//!   run stops before bus-off.
//!
//! Three runs of eight frames, each of which must be reported failed:
//!
//! 1. Bus errors not reported, each interrupt logging the controller's flags
//!    and transmit buffer state before the driver handles them. The logging
//!    delays the driver by about 120 µs, past the end of the error frame.
//! 2. The same without the logging, so the driver handles the bus error
//!    while the frame is still pending.
//! 3. Bus errors reported, without the logging.
//!
//! Each frame logs how long its report took, or that none came and the
//! state a moment later. Then a frame fails with the interrupt masked, and
//! `stop` must report it failed, not aborted.
//! Normal mode, so it
//! drives PA12: only with nothing else on CN4's pins 5 and 13. Reading PSR
//! clears its error codes, so the driver's own bus error reports are
//! unreliable here.
//!
//! ```sh
//! cargo run-mcan-dar
//! ```

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use core::sync::atomic::{AtomicBool, Ordering};

use can_hal::{BusStatus, CanFrame, CanId, ConfirmedTransmit, Event, Failure, Outcome, SamplePoint};
use can_hal_mcan::{BitTiming, Can, Clock, Config, Mode, Peripheral, State};
use defmt::{Debug2Format, error, info, warn};
use defmt_rtt as _;
use embassy_executor::Spawner;
use embassy_stm32::gpio::{AfType, Flex, OutputType, Pull, Speed};
use embassy_stm32::interrupt::typelevel::{FDCAN1_IT0, Handler, Interrupt};
use embassy_stm32::rcc::{self, Pll, PllMul, PllPreDiv, PllQDiv, PllRDiv, PllSource, Sysclk};
use embassy_time::{Duration, Instant, Timer, with_timeout};
use panic_probe as _;

/// FDCAN1's kernel clock: PLL Q, 80 MHz.
const CAN_CLOCK_HZ: u32 = 80_000_000;
const EVENTS: usize = 32;
const BITRATE: u32 = 500_000;
/// How long to wait for a frame's report: a classic frame and its error
/// frame take well under a millisecond at 500 kbit/s.
const REPORT_TIMEOUT: Duration = Duration::from_millis(20);
/// Frames per run: eight acknowledgement or bit errors raise the TEC by 64.
/// Acknowledgement errors stop raising it at 128 (error passive); bit errors
/// don't, and 25 frames in all stay short of bus-off at 256.
const FRAMES: u16 = 8;

/// FDCAN1's registers.
const FDCAN1: usize = 0x4000_6400;
const ECR: usize = 0x40;
const PSR: usize = 0x44;
const IR: usize = 0x50;
const TXBRP: usize = 0xC8;
const TXBTO: usize = 0xD4;
const TXBCF: usize = 0xD8;

/// Embassy's time, for the driver's timestamps and timeouts.
struct EmbassyClock;

impl Clock for EmbassyClock {
    type Instant = embassy_time::Instant;

    fn now() -> Self::Instant {
        embassy_time::Instant::now()
    }

    fn deadline(timeout: core::time::Duration) -> Self::Instant {
        let micros = u64::try_from(timeout.as_micros()).unwrap_or(u64::MAX);
        embassy_time::Instant::now().saturating_add(Duration::from_micros(micros))
    }

    fn has_passed(deadline: &Self::Instant) -> bool {
        embassy_time::Instant::now() >= *deadline
    }
}

type Channel = Can<EmbassyClock, EVENTS>;

static STATE: State<EmbassyClock, EVENTS> = State::new();

/// Whether each interrupt logs the controller's state first.
static LOG: AtomicBool = AtomicBool::new(false);

/// One of FDCAN1's registers.
fn read(offset: usize) -> u32 {
    // SAFETY: a register of FDCAN1, whose clock is on before the interrupt
    // is enabled or anything is read.
    unsafe { core::ptr::read_volatile((FDCAN1 + offset) as *const u32) }
}

/// The controller's flags and transmit buffers, as `what` found them.
fn snapshot(what: &str) {
    let (ir, brp, bto, bcf, psr, ecr) = (read(IR), read(TXBRP), read(TXBTO), read(TXBCF), read(PSR), read(ECR));
    info!(
        "{}: IR {=u32:#010x} [{}] TXBRP {=u32:03b} TXBTO {=u32:03b} TXBCF {=u32:03b} LEC {} TEC {}",
        what,
        ir,
        Flags(ir),
        brp,
        bto,
        bcf,
        psr & 0b111,
        ecr & 0xFF
    );
}

/// The IR flags this test is about, by name.
struct Flags(u32);

impl defmt::Format for Flags {
    fn format(&self, f: defmt::Formatter) {
        const NAMES: [(u32, &str); 8] = [(0, "RF0N"), (7, "TC"), (8, "TCF"), (10, "TEFN"), (16, "ELO"), (17, "EP"), (21, "PEA"), (23, "ARA")];
        for (bit, name) in NAMES {
            if self.0 & (1 << bit) != 0 {
                defmt::write!(f, " {}", name);
            }
        }
    }
}

struct CanInterrupt;

impl Handler<FDCAN1_IT0> for CanInterrupt {
    unsafe fn on_interrupt() {
        if LOG.load(Ordering::Relaxed) {
            snapshot("irq");
        }
        STATE.on_interrupt();
    }
}

embassy_stm32::bind_interrupts!(struct Irqs {
    FDCAN1_IT0 => CanInterrupt;
});

/// HSI16 through the PLL: 160 MHz system clock (R), 80 MHz for FDCAN (Q).
fn clocks() -> embassy_stm32::Config {
    let mut config = embassy_stm32::Config::default();
    config.rcc.pll = Some(Pll {
        source: PllSource::HSI,
        prediv: PllPreDiv::DIV4,
        mul: PllMul::MUL80,
        divp: None,
        divq: Some(PllQDiv::DIV4),
        divr: Some(PllRDiv::DIV2),
    });
    config.rcc.sys = Sysclk::PLL1_R;
    config.rcc.boost = true;
    config.rcc.mux.fdcansel = rcc::mux::Fdcansel::PLL1_Q;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = embassy_stm32::init(clocks());

    let mut rx = Flex::new(p.PA11);
    let mut tx = Flex::new(p.PA12);
    if !jumper_safe(&mut rx, &mut tx).await {
        loop {
            Timer::after_secs(1).await;
        }
    }

    // FDCAN1 on alternate function 9. RX pulled up, so that with no jumper
    // it idles recessive and the controller can join.
    rx.set_as_af_unchecked(9, AfType::input(Pull::Up));
    tx.set_as_af_unchecked(9, AfType::output(OutputType::PushPull, Speed::VeryHigh));

    // FDCAN1's bus clock; its kernel clock is PLL Q, by the mux above.
    embassy_stm32::pac::RCC.apb1enr1().modify(|w| w.set_fdcanen(true));
    let _ = embassy_stm32::pac::RCC.apb1enr1().read();

    let nominal = BitTiming::solve_nominal(CAN_CLOCK_HZ, BITRATE, SamplePoint::from_per_mille(875)).unwrap();
    let config = |bus_errors| Config::new(nominal).with_mode(Mode::Normal).with_retransmit(false).with_bus_errors(bus_errors);
    // SAFETY: FDCAN1's registers and message RAM on the STM32G4, used by
    // nothing else.
    let peripheral = unsafe { Peripheral::new(0x4000_6400, 0x4000_A400) };
    let mut can = Can::new(peripheral, &STATE, config(false)).unwrap();
    FDCAN1_IT0::unpend();
    // SAFETY: its handler is bound above.
    unsafe { FDCAN1_IT0::enable() };

    let mut failures = 0;
    for (bus_errors, log) in [(false, true), (false, false), (true, false)] {
        LOG.store(log, Ordering::Relaxed);
        can.reconfigure(config(bus_errors)).unwrap();
        can.start().unwrap();
        Timer::after_millis(10).await;
        info!("--- single shot, bus errors {}, logging {}: synchronised {}", bus_errors, log, can.is_synchronized());
        let mut reported = 0;
        for n in 0..FRAMES {
            reported += u16::from(one_frame(&mut can, n).await);
            Timer::after_millis(50).await;
        }
        info!("--- {} of {} reported failed in time; {}", reported, FRAMES, Debug2Format(&can.error_counters()));
        failures += FRAMES - reported;
    }
    LOG.store(false, Ordering::Relaxed);
    failures += u16::from(!stop_after_failure(&mut can).await);
    if failures == 0 {
        info!("dar: all passed");
    } else {
        error!("dar: {} failures", failures);
    }

    loop {
        Timer::after_secs(1).await;
    }
}

/// Checks the wiring before PA12 is driven, with pulls only: PA12 must read
/// high on its pull-up (low: it's tied to ground, as CN4-4 next to it is), and
/// whether PA11, floating, follows PA12's pull up and down says whether the
/// jumper joins them. True if PA12 is safe to drive.
async fn jumper_safe(rx: &mut Flex<'_>, tx: &mut Flex<'_>) -> bool {
    rx.set_as_input(Pull::None);
    let mut follows = true;
    for pull in [Pull::Up, Pull::Down, Pull::Up, Pull::Down] {
        tx.set_as_input(pull);
        Timer::after_millis(5).await;
        let high = pull == Pull::Up;
        if tx.is_high() != high {
            warn!("PA12 reads {} on a pull {}: tied to something, not driving it", tx.is_high(), Debug2Format(&pull));
            return false;
        }
        follows &= rx.is_high() == high;
    }
    if follows {
        info!("jumper: PA11 follows PA12, acknowledgement errors expected");
    } else {
        info!("no jumper between PA12 and PA11: bit errors expected");
    }
    true
}

/// Sends a frame and waits for its report, logging what came and when. True
/// if it was reported in time.
async fn one_frame(can: &mut Channel, n: u16) -> bool {
    let frame = CanFrame::new(CanId::new_standard(0x100 + n).unwrap(), &[n.to_le_bytes()[0]]).unwrap();
    let start = Instant::now();
    let tx = match can.try_transmit(&frame) {
        Ok(tx) => tx,
        Err(e) => {
            warn!("frame {}: transmit {}", n, Debug2Format(&e));
            return false;
        }
    };
    loop {
        match with_timeout(REPORT_TIMEOUT, can.next_event()).await {
            Ok(Event::Transmitted { id, outcome }) if id == tx => {
                info!("frame {}: {} after {} us", n, Debug2Format(&outcome), start.elapsed().as_micros());
                return outcome == Outcome::Failed(Failure::GaveUp);
            }
            Ok(other) => info!("frame {}: meanwhile {}", n, Debug2Format(&other)),
            Err(_) => {
                warn!("frame {}: no report within {} ms", n, REPORT_TIMEOUT.as_millis());
                snapshot("poll");
                return false;
            }
        }
    }
}

/// A frame fails while the interrupt is masked, so the driver hasn't seen it
/// by the time the channel is stopped: it must be reported failed, not
/// aborted. The channel is still running from the last run. True if it was.
async fn stop_after_failure(can: &mut Channel) -> bool {
    FDCAN1_IT0::disable();
    let frame = CanFrame::new(CanId::new_standard(0x1FF).unwrap(), &[0xFF]).unwrap();
    let tx = can.try_transmit(&frame).unwrap();
    Timer::after_millis(5).await;
    snapshot("before stop");
    can.stop().unwrap();
    FDCAN1_IT0::unpend();
    // SAFETY: its handler is bound above.
    unsafe { FDCAN1_IT0::enable() };
    match with_timeout(REPORT_TIMEOUT, can.next_event()).await {
        Ok(Event::Transmitted { id, outcome }) if id == tx => {
            info!("stopped after a failure: {}", Debug2Format(&outcome));
            outcome == Outcome::Failed(Failure::GaveUp)
        }
        other => {
            warn!("stopped after a failure: {}", Debug2Format(&other));
            false
        }
    }
}
