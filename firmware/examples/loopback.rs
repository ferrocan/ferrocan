//! `can-hal-bxcan` in internal loopback: every kind of classic frame
//! (standard and extended IDs, data and remote, every DLC from 0 to 15) is
//! sent and must come back both as a received frame and as a transmission
//! reported sent. Then three frames are handed over at once, a fourth must
//! find no room, and an abort of the last is reported in its place in order.
//!
//! Loopback is combined with silent mode, so the controller drives nothing on
//! its TX pin and takes nothing from its RX pin: safe whatever is wired, bus
//! or not. On success the LED blinks slowly; on a failure it blinks fast.
//!
//! ```sh
//! cargo run-nucleo-f072rb --example loopback
//! ```

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use can_hal::{BusState, BusStatus, CanFrame, CanId, ConfirmedTransmit, Event, Outcome, SamplePoint, Statistics, TransmitId, TryTransmitError};
use can_hal_bxcan::{BitTiming, Can, Config, Mode};
use defmt::{Debug2Format, error, info};
use defmt_rtt as _;
use embassy_executor::Spawner;
use embassy_time::{Duration, Timer, with_timeout};
use ferrocan::board::{self, Board, CAN_CLOCK_HZ, CAN_EVENTS, CAN_STATE, EmbassyClock};
#[cfg(not(feature = "panic-dfu"))]
use panic_probe as _;

type Channel = Can<EmbassyClock, CAN_EVENTS>;

const BITRATE: u32 = 500_000;
const TIMEOUT: Duration = Duration::from_millis(100);
const DATA: [u8; 8] = [0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut board = Board::init();
    let timing = BitTiming::solve(CAN_CLOCK_HZ, BITRATE, SamplePoint::from_per_mille(875)).unwrap();
    info!("bit timing {}: {} bit/s", timing, timing.bitrate(CAN_CLOCK_HZ));
    let mut can = Can::new(board.can, &CAN_STATE, Config::new(timing).with_mode(Mode::SilentLoopback)).unwrap();
    board::unmask_can_interrupt();
    can.start();
    info!("synchronised: {}", can.is_synchronized());

    let mut failures = 0u32;
    failures += every_frame(&mut can).await;
    failures += three_at_once(&mut can).await;

    info!("bus state {}, counters {}", Debug2Format(&can.bus_state()), Debug2Format(&can.error_counters()));
    info!("statistics {}", Debug2Format(&can.statistics()));
    if can.bus_state() != Ok(BusState::ErrorActive) {
        error!("not error active");
        failures += 1;
    }
    if failures == 0 {
        info!("loopback: all passed");
    } else {
        error!("loopback: {} failures", failures);
    }

    let period = if failures == 0 { 500 } else { 100 };
    loop {
        board.leds.rx.toggle();
        Timer::after_millis(period).await;
    }
}

/// Each kind of frame, one at a time: it must come back received unchanged
/// and reported sent.
async fn every_frame(can: &mut Channel) -> u32 {
    let ids = [CanId::new_standard(0x123).unwrap(), CanId::new_extended(0x1234_5678).unwrap()];
    let mut failures = 0;
    let mut frames = 0;
    for id in ids {
        for dlc in 0..=15 {
            for frame in [CanFrame::new_with_dlc(id, &DATA[..dlc.min(8)], dlc).unwrap(), CanFrame::new_remote(id, dlc).unwrap()] {
                frames += 1;
                let tx = can.try_transmit(&frame).unwrap();
                let (mut received, mut sent) = (false, false);
                while !(received && sent) {
                    match next(can).await {
                        Some(Event::Received(r)) if *r.frame() == frame => received = true,
                        Some(Event::Transmitted { id, outcome: Outcome::Sent(_) }) if id == tx => sent = true,
                        other => {
                            error!("{}: unexpected {}", Debug2Format(&frame), Debug2Format(&other));
                            failures += 1;
                            break;
                        }
                    }
                }
            }
        }
    }
    info!("every frame: {} frames, {} failures", frames, failures);
    failures
}

/// Three frames handed over at once, a fourth finding no room, and the third
/// aborted: the reports come in the order handed over.
async fn three_at_once(can: &mut Channel) -> u32 {
    let frame = |n: u8| CanFrame::new(CanId::new_standard(0x100 + u16::from(n)).unwrap(), &[n]).unwrap();
    let ids: [TransmitId; 3] = [0, 1, 2].map(|n| can.try_transmit(&frame(n)).unwrap());
    let mut failures = 0;
    if !matches!(can.try_transmit(&frame(3)), Err(TryTransmitError::Full)) {
        error!("a fourth frame found room");
        failures += 1;
    }
    can.abort(ids[2]).unwrap();

    let mut reports = [None; 3];
    let mut received = 0;
    let mut reported = 0;
    while reported < 3 {
        match next(can).await {
            Some(Event::Transmitted { id, outcome }) => {
                if id != ids[reported] {
                    error!("report {} for {}, expected {}", reported, Debug2Format(&id), Debug2Format(&ids[reported]));
                    failures += 1;
                }
                reports[reported] = Some(outcome);
                reported += 1;
            }
            Some(Event::Received(_)) => received += 1,
            other => {
                error!("unexpected {}", Debug2Format(&other));
                failures += 1;
                break;
            }
        }
    }
    // The third was aborted in time, or was already on its way and sent.
    let third = reports[2].map(|o| matches!(o, Outcome::Aborted(_)));
    let expected_received = if third == Some(true) { 2 } else { 3 };
    while received < expected_received {
        match next(can).await {
            Some(Event::Received(_)) => received += 1,
            other => {
                error!("waiting for frames: {}", Debug2Format(&other));
                failures += 1;
                break;
            }
        }
    }
    info!("three at once: reports {}, {} received, {} failures", Debug2Format(&reports), received, failures);
    if !reports[..2].iter().all(|o| matches!(o, Some(Outcome::Sent(_)))) {
        error!("the first two weren't both sent");
        failures += 1;
    }
    failures
}

async fn next(can: &mut Channel) -> Option<Event<CanFrame, embassy_time::Instant>> {
    with_timeout(TIMEOUT, can.next_event()).await.ok()
}
